import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createApp } from '../server/app.js';
import { DEFAULT_CONNECTIONS } from '../server/connections.js';
import { encodeWav } from '../server/audio.js';

// Real UI and project API, isolated disk library, deterministic TTS. No production data.
const temp = await mkdtemp(path.join(os.tmpdir(), 'script-glow-studio-'));
let calls = 0;
const names = ['DAVID', 'ELIZABETH', 'ROBERT'];
const source = [1, 2].map(scene => `SCENE ${scene}\n\n${Array.from({ length: 18 }, (_, line) => `${names[line % 3]}: Scene ${scene}, line ${line + 1}. A little practice brings the words to life.\n`).join('\n')}`).join('\n');
const preferences = { source, name: 'Studio acceptance', role: 'DAVID', cast: { DAVID: 'ActorVoice', ELIZABETH: 'Stock-Amber', ROBERT: 'Stock-Ash' }, guesses: { DAVID: 'male', ELIZABETH: 'female', ROBERT: 'male' }, genders: {}, manualVoices: { DAVID: true, ELIZABETH: true, ROBERT: true }, sceneId: 'scene-1', gap: 0, directions: false, hide: false, follow: true, loop: false, rate: 1, mode: 'full' };
const wav = encodeWav(Buffer.alloc(48000, 8));
const app = createApp({ cacheDir: path.join(temp, 'cache'), projectsDir: path.join(temp, 'projects'), previewDir: path.join(temp, 'previews'), connections: { ...DEFAULT_CONNECTIONS, casting: { preferredActorVoice: 'ActorVoice', aliases: { default: 'ActorVoice' } } }, serviceFetch: async url => {
  if (url.endsWith('/health')) return Buffer.from('{}');
  if (url.endsWith('/v1/voices')) return Buffer.from(JSON.stringify(['default', 'ActorVoice', 'Stock-Amber', 'Stock-Mica', 'Stock-Ash', 'Stock-Granite']));
  if (url.endsWith('/v1/tts')) { calls++; return wav; }
  throw new Error(`Unexpected service call ${url}`);
} });
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  const created = await fetch(`${base}/api/projects`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ preferences }) });
  assert.equal(created.status, 201);
  const project = await created.json();
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const saved = () => page.waitForFunction(() => document.querySelector('#project-save-status')?.textContent === 'Saved locally');
  const color = (selector, value) => page.locator(selector).evaluate((node, value) => { node.value = value; node.dispatchEvent(new Event('change', { bubbles: true })); }, value);
  const audioState = () => page.locator('#scene-audio').evaluate(audio => ({ src: audio.currentSrc, time: audio.currentTime, paused: audio.paused }));
  await page.goto(base); await saved();
  await page.waitForFunction(() => document.querySelector('[data-cast]')?.options.length > 1);
  assert.equal(await page.locator('.workspace-grid').isVisible(), true);
  assert.equal(await page.locator('.cast-screen').isVisible(), false);
  assert.equal(await page.locator('.settings-panel .cast-row').count(), 0);
  assert.equal(await page.locator('.script-page .character-highlight').count(), 6);
  assert.equal(await page.locator('.settings-panel > :nth-child(2)').getAttribute('class'), 'settings-card render-card');
  assert.equal(await page.getByRole('button', { name: 'New project', exact: true }).isVisible(), true);
  assert.equal(await page.locator('.project-library [data-action="import"]').count(), 1);
  assert.equal(await page.getByLabel('Open saved project', { exact: true }).count(), 1);
  assert.equal(await page.locator('.brand-mark').evaluate(img => img.complete && img.naturalWidth > 0), true);
  await page.locator('[data-screen="cast"]').click();
  await page.locator('.cast-screen').waitFor({ state: 'visible' });
  assert.equal(await page.locator('.cast-screen').isVisible(), true);
  assert.equal(await page.locator('.workspace-grid').isVisible(), false);
  assert.equal(await page.locator('.cast-screen .cast-row').count(), 3);
  assert.equal(await page.locator('[data-cast="ELIZABETH"] option[value="ActorVoice"]').isDisabled(), true);
  assert.equal(await page.locator('[data-cast="ELIZABETH"] option[value="default"]').isDisabled(), true);
  await page.locator('[data-action="highlight-character"][data-character="ELIZABETH"]').click(); await saved();
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('data-character')), 'ELIZABETH', 'Keyboard focus stays on the edited card');
  assert.equal(await page.locator('#my-role').inputValue(), 'DAVID');
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/studio-cast-desktop.png', fullPage: true });
  await page.locator('[data-screen="rehearsal"]').click();
  assert.equal(await page.locator('#highlight-character').inputValue(), 'ELIZABETH');
  assert.match(await page.locator('.character-highlight .character-label').first().innerText(), /ELIZABETH/);
  await color('#character-color', '#22c55e'); await color('#spoken-color', '#c084fc'); await saved();
  await page.locator('[data-action="render"]').click();
  await page.locator('a[download][href$="-full.wav"]').waitFor({ timeout: 20000 });
  const originalAudio = await page.locator('a[download][href$="-full.wav"]').getAttribute('href');
  const renderedCalls = calls;
  await page.locator('[data-action="play"]').click();
  await page.waitForFunction(() => !document.querySelector('#scene-audio').paused);
  await page.locator('#scene-audio').evaluate(audio => { audio.currentTime = 10.2; audio.dispatchEvent(new Event('timeupdate')); });
  await page.waitForFunction(() => document.querySelector('.character-highlight.active'));
  const backgrounds = await page.locator('.script-page').evaluate(paper => ({ active: getComputedStyle(paper.querySelector('.character-highlight.active > p')).backgroundColor, other: getComputedStyle(paper.querySelector('.character-highlight:not(.active) > p')).backgroundColor }));
  assert.notEqual(backgrounds.active, backgrounds.other, 'Spoken highlight differs from persistent marks');
  await page.locator('[data-screen="cast"]').click();
  const duringCast = await audioState(); assert.equal(duringCast.paused, false);
  await page.locator('[data-screen="rehearsal"]').click();
  assert.equal((await audioState()).src, duringCast.src);
  assert.ok((await audioState()).time >= duringCast.time);
  await page.locator('#scene-audio').evaluate(audio => audio.pause());
  await color('#character-color', '#60a5fa'); await saved();
  assert.equal((await audioState()).src, duringCast.src);
  assert.equal(calls, renderedCalls, 'Visual settings never call TTS');
  await page.screenshot({ path: 'artifacts/studio-rehearsal-desktop.png', fullPage: true });
  await page.emulateMedia({ media: 'print' });
  assert.notEqual(await page.locator('.character-highlight.active > p').evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)', 'Static marks survive print even on the active line');
  await page.emulateMedia({ media: 'screen' });
  await page.locator('#highlight-character').selectOption('@role'); await saved();
  await page.locator('#hide-lines').check(); await saved();
  assert.equal(await page.locator('.my-line.character-highlight .hidden-line').count(), 6);
  assert.equal(await page.locator('.my-line > p').count(), 0, 'Highlight does not reveal hidden dialogue');
  await page.locator('#hide-lines').uncheck();
  await page.locator('#scene-select').selectOption('scene-2'); await saved();
  await page.locator('#scene-select').selectOption('scene-1'); await saved();
  assert.equal(await page.locator('a[download][href$="-full.wav"]').getAttribute('href'), originalAudio);
  await page.reload(); await saved();
  assert.equal(await page.locator('#character-color').inputValue(), '#60a5fa');
  assert.equal(await page.locator('#spoken-color').inputValue(), '#c084fc');
  assert.equal(await page.locator('a[download][href$="-full.wav"]').getAttribute('href'), originalAudio);
  assert.equal(calls, renderedCalls);
  await page.route('**/api/connections', route => route.fulfill({ status: 503, json: { error: 'Profile unavailable' } }));
  await page.reload(); await saved();
  await page.waitForFunction(() => document.querySelector('.notice')?.textContent.includes('profile unavailable'));
  assert.equal(await page.locator('[data-cast="DAVID"]').inputValue(), 'ActorVoice', 'Failed profile fetch never silently recasts');
  assert.equal(await page.locator('a[download][href$="-full.wav"]').getAttribute('href'), originalAudio);
  await page.unroute('**/api/connections');
  await page.reload(); await saved();
  const doc = await (await fetch(`${base}/api/projects/${project.id}`)).json();
  assert.equal(doc.preferences.spokenColor, '#c084fc');
  assert.equal(doc.renders.length, 1);
  const backup = await (await fetch(`${base}/api/projects/${project.id}/backup`)).arrayBuffer();
  const restored = await fetch(`${base}/api/projects/restore`, { method: 'POST', headers: { 'Content-Type': 'application/octet-stream' }, body: backup });
  assert.equal(restored.status, 201);
  const restoredDoc = await restored.json();
  assert.equal(restoredDoc.preferences.spokenColor, '#c084fc');
  assert.equal(restoredDoc.renders.length, 1);
  await page.locator('[data-screen="cast"]').click();
  await page.locator('[data-action="choose-role"][data-character="ROBERT"]').click(); await saved();
  assert.equal(await page.locator('#my-role').inputValue(), 'ROBERT');
  await page.locator('[data-screen="rehearsal"]').click();
  assert.match(await page.locator('.character-highlight .character-label').first().innerText(), /ROBERT/);
  await page.goBack(); assert.equal(await page.locator('.cast-screen').isVisible(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  assert.equal(Math.round((await page.locator('.topbar').boundingBox()).y), 0, 'Mobile navigation is at the top');
  const newProject = page.getByRole('button', { name: 'New project', exact: true });
  const entryBounds = await newProject.boundingBox();
  assert.ok(entryBounds && entryBounds.y >= 64 && entryBounds.y + entryBounds.height < 844 - 157, 'New project is above the fold, not covered by mobile navigation or player');
  assert.equal(await newProject.evaluate(button => { const r = button.getBoundingClientRect(); return button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)); }), true, 'New project is not obscured');
  await page.screenshot({ path: 'artifacts/studio-cast-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No horizontal document overflow on cast screen');
  await page.locator('[data-screen="rehearsal"]').click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'artifacts/studio-rehearsal-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Screenplay scroll stays inside its pane');
  const chooserEvent = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await (await chooserEvent).setFiles({ name: 'New project discovery.txt', mimeType: 'text/plain', buffer: Buffer.from('SCENE 1\nDAVID: A new script in its own project.\nELIZABETH: The first one is still saved.') });
  await page.waitForFunction(id => document.querySelector('#project-select')?.value !== id && document.querySelector('#project-save-status')?.textContent === 'Saved locally', project.id);
  const addedId = await page.locator('#project-select').inputValue();
  assert.notEqual(addedId, project.id);
  assert.match((await (await fetch(`${base}/api/projects/${addedId}`)).json()).preferences.source, /A new script in its own project/);
  const preserved = await (await fetch(`${base}/api/projects/${project.id}`)).json();
  assert.equal(preserved.preferences.source, source);
  assert.equal(preserved.renders[0].result.fullUrl, originalAudio, 'New project preserves earlier audio');
  await page.getByLabel('Open saved project', { exact: true }).selectOption(project.id); await saved();
  assert.equal(calls, renderedCalls, 'Creating and reopening projects needs no TTS');
  const latest = await (await fetch(`${base}/api/projects/${project.id}`)).json();
  const autoRole = await fetch(`${base}/api/projects/${project.id}`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ revision: latest.revision, preferences: { ...latest.preferences, role: 'DAVID', manualVoices: { ...latest.preferences.manualVoices, DAVID: false } } }) });
  assert.equal(autoRole.status, 200);
  await page.route('**/api/connections', async route => {
    const response = await route.fetch(); const profile = await response.json();
    profile.casting.preferredActorVoice = 'Stock-Granite'; profile.casting.aliases = {};
    await route.fulfill({ json: profile });
  });
  await page.reload();
  await page.waitForFunction(() => document.querySelector('[data-cast="DAVID"]')?.value === 'Stock-Granite'); await saved();
  assert.equal(await page.locator('a[download][href$="-full.wav"]').count(), 0, 'Changed automatic voice never retains mismatched audio');
  assert.equal(calls, renderedCalls);
  assert.deepEqual(errors, []);
  console.log(`PASS: cast navigation/cards, aliases, independent role/highlight, custom colors, distinct playback, uninterrupted navigation, hidden lines, print, saved scene/refresh/backup audio, role selection, history, desktop/mobile. ${calls} mock TTS calls; no real GPU or project data.`);
} finally {
  await browser?.close(); await new Promise(resolve => server.close(resolve));
  if (!temp.startsWith(path.join(os.tmpdir(), 'script-glow-studio-'))) throw new Error('Unexpected temporary path');
  await rm(temp, { recursive: true, force: true });
}
